type Dict = typeof dict;
export type NamespaceKey = keyof Dict;

export function translate(lang: Lang, ns: NamespaceKey, key: string): string {
  const nsDict = dict[ns] as any;
  const entry = nsDict?.[lang]?.[key];
  return entry ?? key;
}
